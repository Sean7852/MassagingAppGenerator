"""Record what a client was generated from: clients/<p>/.manifest.json and GENERATED.md.

    python harness/manifest.py --check <python|typescript|all>
        exit 1 if a client was generated from a different spec than the current one

The spec hash covers everything the generator reads for that platform, with line endings
normalized, so it is the same on every OS and checkout.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from harness.platforms import Platform, resolve  # noqa: E402
from harness.spec_gate import spec_version  # noqa: E402

HARNESS_FILES = ["CLAUDE.md", ".claude/agents/client-generator.md", ".claude/agents/client-fixer.md"]


def _hash(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for path in sorted(paths, key=lambda q: q.relative_to(ROOT).as_posix()):
        h.update(path.relative_to(ROOT).as_posix().encode() + b"\0")
        h.update(path.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return h.hexdigest()


def spec_inputs(p: Platform) -> list[Path]:
    spec = ROOT / "spec"
    return [spec / "README.md", *sorted((spec / "core").glob("*.md")),
            *sorted((spec / "extensions").glob("*.md")), p.spec,
            *sorted((ROOT / "conformance" / "scenarios").glob("*.yaml"))]


def spec_hash(p: Platform) -> str:
    return _hash(spec_inputs(p))


def harness_hash() -> str:
    return _hash([ROOT / f for f in HARNESS_FILES])


def claude_version() -> str:
    try:
        out = subprocess.run(["claude", "--version"], capture_output=True, text=True, timeout=30,
                             shell=sys.platform == "win32")
        return out.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def write(p: Platform, result: dict[str, Any]) -> None:
    manifest = {
        "platform": p.name,
        "spec_version": spec_version(),
        "spec_hash": spec_hash(p),
        "spec_inputs": [f.relative_to(ROOT).as_posix() for f in spec_inputs(p)],
        "harness_hash": harness_hash(),
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "generator": {"tool": claude_version(), **result.pop("generator", {})},
        "result": result,
    }
    (p.dir / ".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8",
                                          newline="\n")
    (p.dir / "GENERATED.md").write_text(f"""# GENERATED — do not edit

Everything in this folder was generated by the harness from the spec. Do not edit it by hand:
change `spec/` (or the harness) and regenerate.

- Platform: `{p.name}` (rules in `spec/platforms/{p.spec.name}`)
- Spec version: {manifest['spec_version']}, hash `{manifest['spec_hash'][:12]}`
  (inputs listed in `.manifest.json`)
- Regenerate: `python harness/regenerate.py --platform {p.name}` or `/generate {p.name}` in Claude Code
- Choices the generator made where the spec left room: `ASSUMPTIONS.md`
""", encoding="utf-8", newline="\n")


def check(p: Platform) -> str | None:
    """Return a problem description, or None if the client matches the current spec."""
    path = p.dir / ".manifest.json"
    if not path.exists():
        return "no .manifest.json (not generated by the harness?)"
    recorded = json.loads(path.read_text(encoding="utf-8")).get("spec_hash")
    if recorded != spec_hash(p):
        return "generated from an older spec; regenerate"
    return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", metavar="PLATFORM", required=True)
    args = ap.parse_args()
    bad = 0
    for p in resolve(args.check):
        problem = check(p) if p.exists() else "no client"
        print(f"{p.name}: {problem or 'up to date with the spec'}")
        bad += problem is not None
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
